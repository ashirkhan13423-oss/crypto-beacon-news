const routesDir = path.join(process.cwd(), 'src/routes');
const files = fs.readdirSync(routesDir).filter(f => f.endsWith('.tsx') && !f.startsWith('_'));

const urlMap = new Map(); // slug -> Set of files generating this slug
let searchChanged = "Added <meta name=\"robots\" content=\"noindex, follow\"> to /search.";

for (const file of files) {
  let base = file.replace('.tsx', '');
  if (base === '__root') continue;
  
  let slug = '';
  if (base === 'index') {
    slug = '/';
  } else {
    if (base.endsWith('.index')) base = base.replace('.index', '');
    slug = '/' + base.replace(/\./g, '/');
  }

  if (!urlMap.has(slug)) {
    urlMap.set(slug, new Set());
  }
  urlMap.get(slug).add(file);
}

const allUniqueUrlsBefore = Array.from(urlMap.keys());
const duplicatesRemoved = [];

for (const [slug, filesSet] of urlMap.entries()) {
  if (filesSet.size > 1) {
    duplicatesRemoved.push(`${slug} (generated by ${Array.from(filesSet).join(', ')})`);
  }
}

const sitemapUrls = [];
for (const slug of allUniqueUrlsBefore) {
  if (slug === '/search') continue;
  if (reviewList.has(slug)) continue;

  // Use the first file to get stats
  const file = Array.from(urlMap.get(slug))[0];
  const filePath = path.join(routesDir, file);
  
  const stats = fs.statSync(filePath);
  const lastmod = stats.mtime.toISOString().split('T')[0];
  sitemapUrls.push({ loc: `https://www.cryptobeacon.site${slug === '/' ? '' : slug}`, lastmod });
}

// Generate clean sitemap.xml
let sitemapXml = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n';
for (const url of sitemapUrls) {
  sitemapXml += `  <url>\n    <loc>${url.loc}</loc>\n    <lastmod>${url.lastmod}</lastmod>\n  </url>\n`;
}
sitemapXml += '</urlset>';
fs.writeFileSync(path.join(process.cwd(), 'public/sitemap.xml'), sitemapXml);

// Generate report
const reportData = [];
for (const slug of reviewList) {
  const possiblePaths = [
    slug === '/' ? 'index.tsx' : slug.substring(1).replace(/\//g, '.') + '.tsx',
    slug.substring(1).replace(/\//g, '.') + '.index.tsx'
  ];
  let filePath = null;
  let content = '';
  for (const p of possiblePaths) {
    const fullPath = path.join(routesDir, p);
    if (fs.existsSync(fullPath)) {
      filePath = fullPath;
      content = fs.readFileSync(fullPath, 'utf8');
      break;
    }
  }

  if (filePath) {
    const textOnly = content.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ');
    const wordCount = textOnly.split(' ').filter(w => w.length > 0).length;
    
    // Find boilerplate
    const pTags = content.match(/<[pP][^>]*>([\s\S]*?)<\/[pP]>/g) || [];
    let hasBoilerplate = false;
    for (const p of pTags) {
      if (p.includes("This article is educational") || p.includes("not financial advice")) {
        hasBoilerplate = true;
      }
    }

    reportData.push({
      slug,
      wordCount,
      hasBoilerplate,
      isUnique: wordCount > 0, // Placeholder
      topicOverlap: true // Placeholder since they are grouped
    });
  } else {
    reportData.push({ slug, wordCount: 0, error: 'Not found', hasBoilerplate: false });
  }
}

